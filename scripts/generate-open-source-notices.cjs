// Keep the offline app notices identical to the reviewed license files.
const fs = require('node:fs');
const path = require('node:path');
const { verify, fileReferences } = require('./verify-distribution-licenses.cjs');
const root = path.resolve(__dirname, '..');
const sources = [
  ['MeloCanvas original code and MIT-marked artwork — MIT (OC excluded)', 'LICENSE'],
  ['MeloCanvas OC — limited asset license, not MIT', 'android-app/apps/mobile/melo/assets/mascot/LICENSE.txt'],
  ['BBPlayer — MIT', 'android-app/LICENSE'],
  ['react-native-logs — MIT', 'android-app/packages/logs/LICENSE'],
  ['NeteaseCloudMusicApi — MIT', 'licenses/NeteaseCloudMusicApi-MIT.txt'],
  ['PlaylistOut directory adapters — Copyright 2026 LengxiQwQ — MIT', 'licenses/playlistout-MIT.txt'],
  ['react-native-bottom-tabs — MIT', 'licenses/react-native-bottom-tabs-MIT.txt'],
  ['Lyricon model — Copyright 2026 Proify, Tomakino — Apache-2.0', 'licenses/Apache-2.0.txt'],
  ['SuperLyricApi 2.4 — HChenX — LGPL-2.1', 'licenses/LGPL-2.1.txt'],
  ['jaudiotagger 3.0.1 — Paul Taylor and contributors — LGPL-2.1-or-later', 'licenses/LGPL-2.1.txt'],
];
const sections = sources.map(([title, file]) => ({ title, text: fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trim() }));
const ledger = JSON.parse(fs.readFileSync(path.join(root, 'release/dependency-licenses.json')));
verify(ledger, root);
const groups = new Map();
for (const entry of [...ledger.npm, ...ledger.maven, ...ledger.native.map(p => ({ name: p.component, files: [p] }))]) {
  for (const item of entry.files) {
    if (item.file === 'licenses/native/zstd/COPYING') continue; // BSD is the selected alternative.
    if (!groups.has(item.sha256)) groups.set(item.sha256, { file: item.file, users: new Set() });
    groups.get(item.sha256).users.add(entry.coordinate || `${entry.name}${entry.version ? '@' + entry.version : ''}`);
  }
}
const dependencies = [...groups.values()].map(({ file, users }) => ({
  title: `${path.basename(file)} · ${[...users][0]}${users.size > 1 ? ' + ' + (users.size - 1) + ' components' : ''}`,
  text: `Applies to: ${[...users].join(', ')}\n\n` + fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trim(),
}));
for (const [index, notice] of dependencies.entries()) {
  if (dependencies.some((other, i) => i !== index && other.title === notice.title)) notice.title += ` · ${[...groups.values()][index].file.replace(/^licenses\//, '')}`;
}
// File digests are also embedded so a binary can be tied to the reviewed source texts.
const digests = [...new Map(fileReferences(ledger).map(f => [f.file, f.sha256])).entries()];
sections.push({ title: 'Third-party acknowledgements and license choices', text: [...ledger.acknowledgements, ...Object.entries(ledger.choices).map(([name, choice]) => `${name}: ${choice}`)].join('\n\n') });
if (new Set([...sections, ...dependencies].map(s => s.title)).size !== sections.length + dependencies.length) throw Error('Ambiguous offline notice title');
const text = '// Generated by scripts/generate-open-source-notices.cjs; edit the license sources.\n' +
  'export const openSourceNotices = ' + JSON.stringify([...sections, ...dependencies], null, '\t') + ' as const\n' +
  'export const licenseFileDigests = ' + JSON.stringify(digests) + ' as const\n';
const output = path.join(root, 'android-app/apps/mobile/melo/open-source-notices.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== text) {
    console.error('Offline license notices are missing or stale. Run node scripts/generate-open-source-notices.cjs.');
    process.exitCode = 1;
  }
} else fs.writeFileSync(output, text);
